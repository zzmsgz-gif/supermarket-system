-- 为什么删：
--   这张表按订单维度把「运费 / 券 / 活动 / 会员 / 积分」拆成多条记录，
--   但**这些金额已经包含在订单的实付金额里**（实付 = 小计 + 运费 − 优惠）。
--   把它们当独立流水再累加一遍 = **重复计算**：
--     实付 88（已含运费 8） + 运费 8 = 96，凭空多出 8 元。
--
-- 现在的做法：
--   金额明细直接查 wallet_transaction（钱包余额变动），
--   那里记的本来就是**真正的资金进出**（RECHARGE 充值 / PAYMENT 支付 / REFUND 退款），
--   不存在重复计算。「这单省了多少」属于订单的金额构成，在订单详情里看。
--
-- 如需清理历史残留（这张表若还在）：
--   DROP TABLE IF EXISTS amount_record;
