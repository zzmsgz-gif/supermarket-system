-- 2026-10-09 修复：积分口径不一致（订单详情 66 分 vs 积分明细 74 分）
-- ----------------------------------------------------------------------------
-- 根因：同一个积分被**两处独立计算**，且传的口径不同：
--   下单时（OrderService）  earnPoints(finalPay)   ← 不含运费 → 66
--   支付时（MemberService） earnPoints(payAmount) ← 含运费   → 74
-- 代码注释写着「同一个口径」，实际差了一个运费，所以用户对不上账。
--
-- 已改代码（下单时也传含运费的实付），本脚本修**历史数据**：
-- 以 point_ledger 为准 —— 那是**实际发出去的积分**，改 orders 才是对齐事实，
-- 反过来改流水会导致用户余额与流水不符。
--
-- 幂等：可重复执行（重复执行时 WHERE 条件不成立，0 行受影响）。
-- 影响面：线上修了 16 笔（订单 365/389/390/477/478/... 与流水差额均等于运费）。
-- ============================================================================

UPDATE orders o
  JOIN point_ledger pl ON pl.ref_order_id = o.id AND pl.type = 'EARN'
   SET o.points_earned = pl.amount
 WHERE o.points_earned <> pl.amount;