-- ============================================================================
-- 2026-10-10 管理端优惠券：新增「每日可领」类型
-- ----------------------------------------------------------------------------
-- 需求：后台创建优惠券时能选「每人限领一次」或「每天可领一次」。
--
-- 现状：coupon 表没有「领取方式」字段，Service 里硬编码
--   `findByUserIdAndCouponId(...).isPresent()` → 一人一券终身一次。
--
-- claim_type 取值：
--   0 = 每人限领一次（**历史数据默认值**，行为与改动前完全一致）
--   1 = 每天可领一次（当天 0 点重置；昨天领过今天还能领）
--
-- ⚠️ 默认值必须是 0：存量券全部按「限领一次」处理，
--    加列时若默认值是 1 会让所有老券一夜之间变成可重复领 —— 直接放开领取限制。
--
-- ⚠️ 执行顺序：**必须先跑本脚本，再 systemctl restart**。
--    ddl-auto 是 validate，实体加了 claimType 但库里没这列 → 启动直接失败。
-- ============================================================================

ALTER TABLE coupon
  ADD COLUMN claim_type TINYINT NOT NULL DEFAULT 0 COMMENT '领取方式：0=每人限领一次 1=每天可领一次' AFTER status;